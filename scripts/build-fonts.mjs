// Bundles Inter (from @fontsource/inter) into the library styles: copies the woff2 files to
// src/styles/fonts and generates src/styles/_fonts.generated.scss with matching @font-face
// rules. The font URLs are relative (`./fonts/...`), so they resolve against both Vite
// (Storybook) and the compiled dist/enchanted.css (dist/fonts, copied by `npm run build`).
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = dirname(createRequire(import.meta.url).resolve('@fontsource/inter/package.json'));
const WEIGHTS = [400, 500, 600, 700];
const SUBSETS = ['latin', 'latin-ext'];

const fontsDir = join(root, 'src/styles/fonts');
rmSync(fontsDir, { recursive: true, force: true });
mkdirSync(fontsDir, { recursive: true });

const blocks = [];
for (const weight of WEIGHTS) {
  const css = readFileSync(join(pkgDir, `${weight}.css`), 'utf8');
  for (const subset of SUBSETS) {
    const name = `inter-${subset}-${weight}-normal`;
    const match = css.match(new RegExp(`/\\* ${name} \\*/\\s*@font-face \\{[^}]*\\}`));
    if (!match) throw new Error(`@font-face for ${name} not found in @fontsource/inter`);
    copyFileSync(join(pkgDir, 'files', `${name}.woff2`), join(fontsDir, `${name}.woff2`));
    blocks.push(
      match[0].replace(/src:[^;]*;/, `src: url(./fonts/${name}.woff2) format('woff2');`),
    );
  }
}

writeFileSync(
  join(root, 'src/styles/_fonts.generated.scss'),
  `// Generated by scripts/build-fonts.mjs - do not edit.\n${blocks.join('\n\n')}\n`,
);
console.log(`Bundled ${blocks.length} Inter @font-face rules.`);
